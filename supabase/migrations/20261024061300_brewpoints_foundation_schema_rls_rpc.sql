-- 4. Private Helper Function for Non-Recursive RLS Role Resolution
CREATE OR REPLACE FUNCTION private.get_my_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT role
  FROM public.profiles
  WHERE id = (SELECT auth.uid())
    AND deleted_at IS NULL;
$$;

