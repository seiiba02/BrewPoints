-- 8. Atomic Stored Procedures (RPCs — SECURITY INVOKER)
CREATE OR REPLACE FUNCTION public.allocate_points_atomic(
  p_customer_id UUID,
  p_staff_id UUID,
  p_amount NUMERIC(10, 2),
  p_points INT,
  p_note TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_caller_uid UUID;
  v_caller_role TEXT;
  v_customer_name TEXT;
  v_account public.loyalty_accounts%ROWTYPE;
  v_tx_id BIGINT;
BEGIN
  v_caller_uid := (SELECT auth.uid());
  IF v_caller_uid IS NOT NULL THEN
    v_caller_role := (SELECT private.get_my_role());
    IF v_caller_role NOT IN ('staff', 'owner') OR v_caller_uid <> p_staff_id THEN
      RAISE EXCEPTION 'Forbidden: staff or owner role required' USING ERRCODE = '42501';
    END IF;
  END IF;

  IF p_amount < 1.00 OR p_amount > 1000.00 THEN
    RAISE EXCEPTION 'Purchase amount must be between 1.00 and 1000.00' USING ERRCODE = '22023';
  END IF;

  IF p_points <= 0 THEN
    RAISE EXCEPTION 'Points credited must be positive' USING ERRCODE = '22023';
  END IF;

  SELECT name INTO v_customer_name
  FROM public.profiles
  WHERE id = p_customer_id AND role = 'customer' AND deleted_at IS NULL;

  IF v_customer_name IS NULL THEN
    RAISE EXCEPTION 'Active customer profile not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO v_account
  FROM public.loyalty_accounts
  WHERE user_id = p_customer_id AND deleted_at IS NULL
  FOR UPDATE;

  IF NOT FOUND THEN
    INSERT INTO public.loyalty_accounts (user_id, current_points, total_points_earned, total_points_redeemed, last_earned_at)
    VALUES (p_customer_id, p_points, p_points, 0, now())
    RETURNING * INTO v_account;
  ELSE
    UPDATE public.loyalty_accounts
    SET current_points = current_points + p_points,
        total_points_earned = total_points_earned + p_points,
        last_earned_at = now(),
        updated_at = now()
    WHERE id = v_account.id
    RETURNING * INTO v_account;
  END IF;

  INSERT INTO public.transactions (user_id, type, points, amount, staff_id, note)
  VALUES (p_customer_id, 'earn', p_points, p_amount, p_staff_id, p_note)
  RETURNING id INTO v_tx_id;

  RETURN jsonb_build_object(
    'transaction_id', v_tx_id,
    'customer_id', p_customer_id,
    'customer_name', v_customer_name,
    'points_credited', p_points,
    'new_balance', v_account.current_points,
    'total_earned', v_account.total_points_earned
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.allocate_points_atomic(UUID, UUID, NUMERIC, INT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.allocate_points_atomic(UUID, UUID, NUMERIC, INT, TEXT) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.confirm_redemption_atomic(
  p_jti UUID,
  p_customer_id UUID,
  p_reward_id BIGINT,
  p_staff_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_caller_uid UUID;
  v_caller_role TEXT;
  v_customer_name TEXT;
  v_reward public.rewards%ROWTYPE;
  v_account public.loyalty_accounts%ROWTYPE;
  v_redemption_id BIGINT;
  v_tx_id BIGINT;
BEGIN
  v_caller_uid := (SELECT auth.uid());
  IF v_caller_uid IS NOT NULL THEN
    v_caller_role := (SELECT private.get_my_role());
    IF v_caller_role NOT IN ('staff', 'owner') OR v_caller_uid <> p_staff_id THEN
      RAISE EXCEPTION 'Forbidden: staff or owner role required' USING ERRCODE = '42501';
    END IF;
  END IF;

  IF EXISTS (SELECT 1 FROM public.redemptions WHERE jti = p_jti) THEN
    RAISE EXCEPTION 'Redemption token has already been used' USING ERRCODE = '23505';
  END IF;

  SELECT name INTO v_customer_name
  FROM public.profiles
  WHERE id = p_customer_id AND role = 'customer' AND deleted_at IS NULL;

  IF v_customer_name IS NULL THEN
    RAISE EXCEPTION 'Active customer profile not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO v_reward
  FROM public.rewards
  WHERE id = p_reward_id AND active = true AND deleted_at IS NULL;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Active reward not found' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO v_account
  FROM public.loyalty_accounts
  WHERE user_id = p_customer_id AND deleted_at IS NULL
  FOR UPDATE;

  IF NOT FOUND OR v_account.current_points < v_reward.points_required THEN
    RAISE EXCEPTION 'Insufficient points balance' USING ERRCODE = '22000';
  END IF;

  INSERT INTO public.redemptions (jti, customer_id, reward_id, points_cost, confirmed_by_staff_id)
  VALUES (p_jti, p_customer_id, p_reward_id, v_reward.points_required, p_staff_id)
  RETURNING id INTO v_redemption_id;

  UPDATE public.loyalty_accounts
  SET current_points = current_points - v_reward.points_required,
      total_points_redeemed = total_points_redeemed + v_reward.points_required,
      updated_at = now()
  WHERE id = v_account.id
  RETURNING * INTO v_account;

  INSERT INTO public.transactions (user_id, type, points, staff_id, redemption_id, note)
  VALUES (
    p_customer_id,
    'redeem',
    v_reward.points_required,
    p_staff_id,
    v_redemption_id,
    'Redeemed ' || v_reward.name
  )
  RETURNING id INTO v_tx_id;

  RETURN jsonb_build_object(
    'redemption_id', v_redemption_id,
    'transaction_id', v_tx_id,
    'customer_id', p_customer_id,
    'customer_name', v_customer_name,
    'reward_id', v_reward.id,
    'reward_name', v_reward.name,
    'points_deducted', v_reward.points_required,
    'new_balance', v_account.current_points
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.confirm_redemption_atomic(UUID, UUID, BIGINT, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.confirm_redemption_atomic(UUID, UUID, BIGINT, UUID) TO authenticated, service_role;
